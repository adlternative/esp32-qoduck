static uint8_t s_cell[W * H];
static int s_size = 128;

/* 滚轮彩蛋（muse_pixel_emote）：0 = 没在播，否则是 MUSE_EMOTE_* */
static int s_emote;
static int64_t s_emote_at;

/* 把位图按 (dx,dy) 贴进网格；dy 由呼吸/蹦跳决定 */
static void blit(int dx, int dy) {
    memset(s_cell, 0, sizeof(s_cell));
    for (int y = 0; y < H; y++) {
        int ty = y + dy;
        if (ty < 0 || ty >= H) continue;
        for (int x = 0; x < W; x++) {
            int tx = x + dx;
            if (tx < 0 || tx >= W) continue;
            s_cell[ty * W + tx] = DUCK[y * W + x];
        }
    }
}

/* 眼睛大致位置（从 64×64 位图里量出来的）：y 32-39，左眼 x 21-26、右眼 x 33-39。
 * 调色板是按出现频率排的：1 是最常见的鸭黄，14 是最暗的（眼睛/眉毛）。 */
#define EYE_Y0 32
#define EYE_Y1 39
#define CLR_FACE 1     /* 鸭黄 */
#define CLR_DARK 14    /* 眼睛/眉毛的深色 */

static void blink_overlay(void) {
    /* 眨眼：在两只眼睛上各画一条横杠（身体色做底 + 深色线） */
    const int spans[2][2] = { { 21, 26 }, { 33, 39 } };
    for (int e = 0; e < 2; e++) {
        int x0 = spans[e][0], x1 = spans[e][1];
        int ymid = (EYE_Y0 + EYE_Y1) / 2;
        for (int y = EYE_Y0; y <= EYE_Y1; y++)
            for (int x = x0; x <= x1; x++) {
                if (s_cell[y * W + x] == 0) continue;
                /* 用鸭黄回填眼睛，再在中间压一条深色横线 = 闭眼 */
                s_cell[y * W + x] = (y == ymid || y == ymid + 1) ? CLR_DARK : CLR_FACE;
            }
    }
}

/*
 * 关机动画：1.5 秒里闭眼、低头下沉，然后抖动淡出。
 * muse_ui.c 同时把背光淡到 0，两边合起来就是“关机”。
 */
#define GOODBYE_SINK   0.35f    /* 低头用多久 */
#define GOODBYE_FADE   0.55f    /* 从这一刻开始消散 */
#define GOODBYE_TOTAL  1.50f    /* 总时长，和 muse_input.c 的 GOODBYE_MS 对齐 */

/* 4×4 有序抖动矩阵：dark 越大，熄灭的格子越多，看着像像素在散开 */
static const uint8_t BAYER[16] = {
    0, 8, 2, 10,
    12, 4, 14, 6,
    3, 11, 1, 9,
    15, 7, 13, 5
};

/* 0 = 没在告别；否则是开始时刻（μs）。故意不用 mode_t，免得状态机抖动把动画重置。 */
static int64_t s_bye_since;
static int s_last_cut;   /* 上一次消散的裁切阀值，串口 dump 时打印 */

static void goodbye(float k) {
    if (k < 0) k = 0;
    float sink = k < GOODBYE_SINK ? k / GOODBYE_SINK : 1.0f;
    blit(0, (int)lroundf(3.0f * sink));
    blink_overlay();

    if (k <= GOODBYE_FADE) return;
    /* 到 k=1 必须归零（否则电源切掉前还留半张脸）：用 1-FADE 做分母，
     * 再加一道 pow 让开头慢、结尾快，看着像“散掉”而不是线性变淡。 */
    float dark = (k - GOODBYE_FADE) / (1.0f - GOODBYE_FADE);
    if (dark > 1.0f) dark = 1.0f;
    int cut = (int)(powf(dark, 1.5f) * 17.0f);
    s_last_cut = cut;
    for (int y = 0; y < H; y++)
        for (int x = 0; x < W; x++)
            if (s_cell[y * W + x] && BAYER[(y & 3) * 4 + (x & 3)] < cut)
                s_cell[y * W + x] = 0;
}void muse_pixel_goodbye_begin(void) {
    s_bye_since = esp_timer_get_time();
}

void muse_pixel_goodbye_end(void) {
    s_bye_since = 0;
}

/* 0 到 1 的进度；-1 表示没在播放。背光那边（muse_ui.c）也在跟这个值。 */
float muse_pixel_goodbye_progress(void) {
    if (s_bye_since == 0) {
        return -1.0f;
    }
    float k = (float)(esp_timer_get_time() - s_bye_since) / (GOODBYE_TOTAL * 1000000.0f);
    return k > 1.0f ? 1.0f : k;
}

/* ── 表情彩蛋：滚轮按/转都逗一下鸭子 ─────────────────────── */
void muse_pixel_emote(int emote) {
    s_emote = emote;
    s_emote_at = esp_timer_get_time();
}

int muse_pixel_emote_active(void) {
    return s_emote;
}

/* 0 → 1 的播放进度；播完返回 -1 并把它清掉 */
static float emote_k(float dur) {
    if (!s_emote) {
        return -1.0f;
    }
    float k = (float)(esp_timer_get_time() - s_emote_at) / (dur * 1000000.0f);
    if (k >= 1.0f) {
        s_emote = 0;
        return -1.0f;
    }
    return k;
}

static void put(int x, int y, uint8_t c) {
    if (x >= 0 && x < W && y >= 0 && y < H) {
        s_cell[y * W + x] = c;
    }
}

/* 小图元：一行一个字符串，'#' 就点亮 */
static void glyph(int x, int y, const char *const *rows, int n, uint8_t c) {
    for (int j = 0; j < n; j++)
        for (int i = 0; rows[j][i]; i++)
            if (rows[j][i] == '#') {
                put(x + i, y + j, c);
            }
}

static const char *const HEART[4] = { ".#.#.", "#####", ".###.", "..#.." };
static const char *const STAR[5] = { "..#..", "..#..", "#####", "..#..", "..#.." };
static const char *const ZEE[3] = { "###", ".#.", "###" };

static uint8_t s_line[W > H ? W : H];

static void shift_x(int dx) {
    if (!dx) {
        return;
    }
    if (dx <= -W || dx >= W) {
        memset(s_cell, 0, sizeof(s_cell));
        return;
    }
    for (int y = 0; y < H; y++) {
        uint8_t *row = &s_cell[y * W];
        memcpy(s_line, row, W);
        for (int x = 0; x < W; x++) {
            int sx = x - dx;
            row[x] = (sx >= 0 && sx < W) ? s_line[sx] : 0;
        }
    }
}

static void shift_y(int dy) {
    if (!dy) {
        return;
    }
    if (dy <= -H || dy >= H) {
        memset(s_cell, 0, sizeof(s_cell));
        return;
    }
    for (int x = 0; x < W; x++) {
        for (int y = 0; y < H; y++) s_line[y] = s_cell[y * W + x];
        for (int y = 0; y < H; y++) {
            int sy = y - dy;
            s_cell[y * W + x] = (sy >= 0 && sy < H) ? s_line[sy] : 0;
        }
    }
}

/* 就地把网格转 90°（转置 + 每行翻转），不用第二块缓冲 */
static void rot90(void) {
    for (int y = 0; y < H; y++)
        for (int x = y + 1; x < W; x++) {
            uint8_t t = s_cell[y * W + x];
            s_cell[y * W + x] = s_cell[x * W + y];
            s_cell[x * W + y] = t;
        }
    for (int y = 0; y < H; y++)
        for (int x = 0; x < W / 2; x++) {
            uint8_t t = s_cell[y * W + x];
            s_cell[y * W + x] = s_cell[y * W + W - 1 - x];
            s_cell[y * W + W - 1 - x] = t;
        }
}

/* 晕过去：两只眼睛画成 X */
static void x_eyes(void) {
    const int spans[2][2] = { { 21, 26 }, { 33, 39 } };
    for (int e = 0; e < 2; e++) {
        int x0 = spans[e][0], x1 = spans[e][1];
        for (int y = EYE_Y0; y <= EYE_Y1; y++)
            for (int x = x0; x <= x1; x++)
                if (s_cell[y * W + x]) {
                    s_cell[y * W + x] = CLR_FACE;
                }
        for (int i = 0; i <= EYE_Y1 - EYE_Y0; i++) {
            int t = i * (x1 - x0) / (EYE_Y1 - EYE_Y0);
            put(x0 + t, EYE_Y0 + i, CLR_DARK);
            put(x1 - t, EYE_Y0 + i, CLR_DARK);
        }
    }
}

/* 在正常一帧画完之后叠彩蛋动作 */
static void apply_emote(void) {
    switch (s_emote) {
    case MUSE_EMOTE_PET: {
        /* 撸一下：再蹦一次，两角飘心 */
        float k = emote_k(1.0f);
        if (k < 0) return;
        shift_y(-(int)lroundf(6.0f * sinf(k * 3.14159f)));
        for (int h = 0; h < 3; h++) {
            float hk = k * 1.7f - h * 0.24f;
            if (hk <= 0.0f || hk >= 1.0f) continue;
            int hx = (h == 1 ? 54 : 5) + (int)lroundf(sinf(hk * 8.0f + h) * 2.0f);
            int hy = 18 - (int)lroundf(hk * 17.0f);
            glyph(hx, hy, HEART, 4, CLR_FACE);
        }
        break;
    }
    case MUSE_EMOTE_DIZZY: {
        /* 转一圈 + 头顶星星 + X 眼 */
        float k = emote_k(1.4f);
        if (k < 0) return;
        x_eyes();
        int step = (int)(k * 4.0f);
        for (int i = 0; i < step; i++) rot90();
        /* 只靠 90° 的跳变太生硬，再叠一点左右摇摆把中间帧补出来 */
        shift_x((int)lroundf(sinf(k * 12.57f) * 3.0f));
        for (int s = 0; s < 3; s++) {
            float a = k * 9.42f + (float)s * 2.094f;
            glyph(32 + (int)lroundf(cosf(a) * 19.0f) - 2,
                  9 + (int)lroundf(sinf(a) * 5.0f) - 2, STAR, 5, CLR_FACE);
        }
        break;
    }
    case MUSE_EMOTE_LOOK: {
        /* 东张西望：左右各摆一下，中间眯一次眼 */
        float k = emote_k(1.0f);
        if (k < 0) return;
        shift_x((int)lroundf(sinf(k * 9.42f) * 5.0f));
        if (k > 0.45f && k < 0.58f) blink_overlay();
        break;
    }
    case MUSE_EMOTE_SLEEPY: {
        /* 打瞌睡：闭眼 + 右上角 Zzz 往上飘 */
        float k = emote_k(1.6f);
        if (k < 0) return;
        blink_overlay();
        for (int z = 0; z < 3; z++) {
            float zk = k * 1.4f - (float)z * 0.2f;
            if (zk <= 0.0f || zk >= 1.0f) continue;
            int zx = 46 + (int)lroundf(zk * 11.0f);
            int zy = 22 - (int)lroundf(zk * 17.0f);
            int sz = z == 0 ? 1 : 2;
            for (int j = 0; j < 3; j++)
                for (int i = 0; i < 3; i++)
                    if (ZEE[j][i] == '#')
                        for (int yy = 0; yy < sz; yy++)
                            for (int xx = 0; xx < sz; xx++) {
                                put(zx + i * sz + xx, zy + j * sz + yy, CLR_FACE);
                            }
        }
        break;
    }
    default:
        break;
    }
}

void muse_pixel_render(const muse_pose_t *pose) {
    const muse_mode_t mode = pose->mode;
    const float t = pose->t;
    float level = pose->level > 1.0f ? 1.0f : pose->level;
    float happy = pose->happy > 1.0f ? 1.0f : pose->happy;

    /* 关机：不呼吸、不摇摆，换成“闭眼 → 低头 → 消散”的告别动画。
     * 用自己的一生一次时钟，而不是 mode_t：进 OFF 前后状态机怎么跳都不会重来。 */
    if (mode == MUSE_MODE_OFF && s_bye_since == 0) {
        s_bye_since = esp_timer_get_time();
    }
    float bye = muse_pixel_goodbye_progress();
    if (bye >= 0.0f) {
        goodbye(bye);
        return;
    }

    /* 呼吸：安静时 ±1.5 格慢浮，说话时 ±3 格快抖 */
    float amp = (mode == MUSE_MODE_SPEAKING) ? (1.5f + level * 2.0f) : 1.5f;
    float speed = (mode == MUSE_MODE_SPEAKING) ? 9.0f : 1.8f;
    int dy = (int)lroundf(sinf(t * speed) * amp);

    /* 左右摇摆：说话时跟着节奏晃，想事情时慢慢晃 */
    float sway_amp = (mode == MUSE_MODE_SPEAKING) ? (1.0f + level * 1.5f)
                   : (mode == MUSE_MODE_THINKING) ? 1.5f : 0.5f;
    float sway_speed = (mode == MUSE_MODE_SPEAKING) ? 4.5f : 1.2f;
    int dx = (int)lroundf(sinf(t * sway_speed) * sway_amp);

    /* 摸头：跳一下 */
    if (happy > 0.02f) dy -= (int)lroundf(5.0f * sinf(happy * 3.14159f));

    /* 在说的时候：每 0.5 秒"点头"一下 */
    if (mode == MUSE_MODE_SPEAKING) dy += (int)lroundf(sinf(t * 6.0f) * (0.8f + level));

    blit(dx, dy);

    /* 眨眼：静息时每 ~3.2 秒眨一次，睁眼时长 0.12 秒 */
    if (mode != MUSE_MODE_ERROR && mode != MUSE_MODE_OFF &&
        fmodf(t, 3.2f) > 3.08f) {
        blink_overlay();
    }

    /* 出错：整体压暗，配合红圈 */
    if (mode == MUSE_MODE_ERROR) {
        for (int i = 0; i < W * H; i++)
            if (s_cell[i]) s_cell[i] = CLR_DARK;
    }

    /* 滚轮触发的彩蛋动作叠在正常一帧上 */
    apply_emote();
}

uint32_t muse_pixel_accent(muse_mode_t mode) {
    switch (mode) {
    case MUSE_MODE_LISTENING: return 0x35C1FF;   /* 在听：蓝 */
    case MUSE_MODE_THINKING:  return 0xB388FF;   /* 在想：紫 */
    case MUSE_MODE_SPEAKING:  return 0xFFB020;   /* 在说：橙 */
    case MUSE_MODE_ERROR:     return 0xFF5252;
    default:                  return 0xF7D04A;   /* 待机：鸭黄 */
    }
}

void muse_pixel_set_size(int px) {
    if (px < 8) px = 8;
    if (px > 512) px = 512;
    s_size = px;
}

void muse_pixel_scale(uint16_t *dst, int stride_px, int x0, int x1, int y0, int y1) {
    if (!dst || s_size <= 0) return;
    const int ox = x0, oy = y0;        /* dst 只覆盖这块矩形，写的时候要减原点 */
    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 >= s_size) x1 = s_size - 1;
    if (y1 >= s_size) y1 = s_size - 1;
    for (int y = y0; y <= y1; y++) {
        int gy = (int)((int64_t)y * H / s_size);
        if (gy >= H) gy = H - 1;
        uint16_t *row = dst + (int64_t)(y - oy) * stride_px;
        for (int x = x0; x <= x1; x++) {
            int gx = (int)((int64_t)x * W / s_size);
            if (gx >= W) gx = W - 1;
            uint8_t c = s_cell[gy * W + gx];
            row[x - ox] = (c == 0) ? 0x0000 : PAL[c];   /* 背景纯黑，和圆形屏底色一致 */
        }
    }
}

/* 验收用：把当前网格按 2 倍抽样打成 ASCII（'#' 有像素，'.' 空） */
void muse_pixel_dump_ascii(void) {
    char line[W / 2 + 1];
    int lit = 0;
    for (int i = 0; i < W * H; i++) lit += s_cell[i] != 0;
    printf("@dump k=%.2f cut=%d lit=%d/%d\n", muse_pixel_goodbye_progress(), s_last_cut, lit, W * H);
    /* 2×2 块：全亮 '#'、部分亮 '+'、全灭 '.'。抖动是按坐标奇偶依次熄灭的，
     * 直接隔点取样会跟图案共振（偶数坐标恰好是第一批被抹掉的）。 */
    for (int y = 0; y < H; y += 2) {
        for (int x = 0; x < W; x += 2) {
            int on = (s_cell[y * W + x] != 0) + (s_cell[y * W + x + 1] != 0) +
                     (s_cell[(y + 1) * W + x] != 0) + (s_cell[(y + 1) * W + x + 1] != 0);
            line[x / 2] = on == 4 ? '#' : (on ? '+' : '.');
        }
        line[W / 2] = '\0';
        printf("%s\n", line);
    }
    fflush(stdout);
}
